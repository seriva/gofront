section("Web declaration generator");

test("a package is generated from its specs", () => {
	assertEqual(run().get("one"), EXPECTED_ONE);
	assertEqual(run().get("two"), EXPECTED_TWO);
});

test("two runs are byte-identical", () => {
	const a = run();
	const b = run();
	for (const pkg of Object.keys(PKGS)) assertEqual(a.get(pkg), b.get(pkg));
});

test("the output does not depend on the order of the specs", () => {
	const reversed = run({ two: TWO, one: ONE });
	assertEqual(reversed.get("one"), EXPECTED_ONE);
	assertEqual(reversed.get("two"), EXPECTED_TWO);
});

test("the output is marked as generated", () => {
	assertContains(
		run().get("one"),
		"Code generated by scripts/gen-web-types.js",
	);
	assertContains(run().get("one"), "DO NOT EDIT");
});

test("a package names another package's type qualified and references it", () => {
	const two = run().get("two");
	assertContains(two, '/// <reference types="gofront/one" />');
	assertContains(two, "interface Device extends one.EventTarget");
	assert(!run().get("one").includes("reference types"));
});

test("a package drops its prefix from the names it declares", () => {
	const two = run().get("two");
	for (const name of ["Buffer", "Device", "BufferDescriptor"])
		assertContains(two, `${name} `);
	assert(!/\bGPU(Buffer|Device)/.test(two), "kept the prefix");
	assertContains(two, "interface GPU {");
});

test("mixins and partials are merged into the interface", () => {
	const one = run().get("one");
	assertContains(one, "querySelector(selectors: string): Node | null;");
	assertContains(one, "extra: int;");
	assertContains(run().get("two"), "label: string;");
	assert(!one.includes("ParentNode"), "declared the mixin");
});

test("overloads merge into one signature", () => {
	const one = run().get("one");
	assertContains(one, "f(a: int, b?: string): void;");
	assertContains(one, "g(a: any): void;");
	assertContains(one, "h(a: int, b?: int): any;");
});

test("a rest parameter is the last parameter of a merged overload", () => {
	const out = run(
		{
			t: "interface X { undefined m(long a, long... rest); undefined m(long a, long b, long c); };",
		},
		{ t: { specs: ["t"] } },
	).get("t");
	assertContains(out, "m(a: int, ...rest: int[]): void;");
});

test("an attribute that is not an identifier is not declared", () => {
	const out = run(
		{
			t: "interface X { attribute DOMString margin-top; attribute long ok; };",
		},
		{ t: { specs: ["t"] } },
	).get("t");
	assertContains(out, "ok: int;");
	assert(!out.includes("margin-top"), out);
});

test("static members and unnamed special operations are not declared", () => {
	const one = run().get("one");
	assert(!/\bs\(/.test(one), "declared a static operation");
	assertContains(one, "item(index: int): string;");
});

test("a nullable type is T | null and a nullable callback is parenthesised", () => {
	const one = run().get("one");
	assertContains(one, "readonly parentNode: Node | null;");
	assertContains(one, "nodeValue: string | null;");
	assertContains(one, "onclick: ((event: Event) => any) | null;");
});

test("dictionaries are marked and keep required members", () => {
	const one = run().get("one");
	assertContains(one, "/** @dictionary */\ninterface Init extends EventInit {");
	assertContains(one, "\tname: string;");
	assertContains(one, "\tmode?: string;");
});

test("an interface with a constructor is a class with new signatures", () => {
	const one = run().get("one");
	assertContains(one, "declare class Event {");
	assertContains(one, "new(type: string, eventInitDict?: EventInit): Event;");
	assertContains(one, "readonly NONE: int;");
});

test("integer types are int, float is float32 and double is number", () => {
	const one = run().get("one");
	assertContains(one, "childCount(): int;");
	assertContains(one, "small?: float32;");
	assertContains(one, "readonly timeStamp: number;");
	assertContains(run().get("two"), "readonly size: int;");
});

test("a namespace is an interface with a capitalised name", () => {
	assertContains(
		run().get("one"),
		"interface Console {\n\tlog(...data: any[]): void;",
	);
});

test("two types that end up with one name are an error", () => {
	let message = "";
	try {
		run(
			{
				two: "interface GPUThing {}; interface Thing {};",
			},
			{ two: { specs: ["two"], prefix: "GPU" } },
		);
	} catch (e) {
		message = e.message;
	}
	assertErrorContains([{ message }], "both two.Thing");
});

test("a spec cannot belong to two packages", () => {
	let message = "";
	try {
		run(
			{ one: "interface A {};" },
			{ a: { specs: ["one"] }, b: { specs: ["one"] } },
		);
	} catch (e) {
		message = e.message;
	}
	assertErrorContains([{ message }], "spec 'one' is in a and b");
});

section("Web declaration generator — the compiler reads the output");

test("the generated declarations parse into the described types", () => {
	const one = parseDeclarationPackage(run().get("one"), "one");
	const node = one.types.get("Node");
	assertEqual(node.extends[0], one.keys.get("EventTarget"));
	assertEqual(node.members.parentNode.alias, one.keys.get("Node"));
	assertEqual(node.members.load.kind, "func");
	assertEqual(node.members.load.returns[0].kind, "promise");
	assertEqual(node.members.many.variadic, true);
	assertEqual(node.members.onclick.kind, "func");
	assert(one.types.get("Init")._dictionary);
	const two = parseDeclarationPackage(run().get("two"), "two");
	assertEqual(two.requires[0], "one");
	assertEqual(two.types.get("Device").extends[0], one.keys.get("EventTarget"));
});

section("Web declaration generator — WebIDL from @webref/idl");

const require = createRequire(import.meta.url);
const idl = require("@webref/idl");
const specs = {};
for (const [name, file] of Object.entries(await idl.listAll()))
	specs[name] = await file.text();
const real = generate(specs, {
	version: require("@webref/idl/package.json").version,
});

test("every package generates from the real specs and parses", () => {
	for (const pkg of Object.keys(PACKAGES)) {
		const parsed = parseDeclarationPackage(real.get(pkg), pkg);
		assert(parsed.types.size > 0, `${pkg} declares no types`);
	}
});

test("the real specs give the types the web packages exist for", () => {
	const types = (pkg) => parseDeclarationPackage(real.get(pkg), pkg).types;
	const dom = types("dom");
	for (const name of [
		"Document",
		"Element",
		"HTMLElement",
		"HTMLInputElement",
		"Event",
		"MouseEvent",
		"Window",
	])
		assert(dom.has(name), `dom.${name}`);
	assert(types("fetch").has("Response"));
	assert(types("canvas").has("CanvasRenderingContext2D"));
	assert(types("websocket").has("WebSocket"));
	for (const name of ["Device", "Buffer", "Texture", "CanvasContext"])
		assert(types("webgpu").has(name), `webgpu.${name}`);
});

test("keyword-named members of the real specs survive", () => {
	const dom = parseDeclarationPackage(real.get("dom"), "dom").types;
	assertEqual(dom.get("Event").members.type.name, "string");
	assertEqual(dom.get("HTMLInputElement").members.type.name, "string");
});

test("no generated property of the real specs has a non-identifier name", () => {
	for (const [pkg, text] of real)
		assert(!/^\s+(readonly )?[\w$]*-[\w$-]*\??:/m.test(text), pkg);
});

test("--package without a name is an error", () => {
	const r = spawnSync(
		process.execPath,
		[join(ROOT, "scripts", "gen-web-types.js"), "--package"],
		{ encoding: "utf8" },
	);
	assertEqual(r.status, 1);
	assertContains(r.stderr, "--package needs a package name");
});

test("each published package is committed and current", () => {
	for (const pkg of PUBLISHED) {
		const path = join(ROOT, "stdlib", "gofront", pkg, `${pkg}.d.ts`);
		assert(existsSync(path), `${path} is missing`);
		assertEqual(readFileSync(path, "utf8"), real.get(pkg));
	}
});

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	process.exit((await summarize()) > 0 ? 1 : 0);
}
