// GoFront test suite — the pdqsort variant generator (scripts/gen-pdq.js)

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { generateAll, VARIANTS } from "../../../scripts/gen-pdq.js";
import {
	assert,
	assertContains,
	assertEqual,
	section,
	summarize,
	test,
} from "../helpers.js";

const ROOT = fileURLToPath(new URL("../../../", import.meta.url));

section("pdqsort variant generator");

test("regenerating the checked-in variants is a no-op", () => {
	for (const { path, content } of generateAll())
		assert(
			readFileSync(join(ROOT, path), "utf8") === content,
			`${path} is out of date; run npm run gen:pdq`,
		);
});

test("four variants are generated, each marked as generated", () => {
	const out = generateAll();
	assertEqual(out.length, 4);
	for (const { content } of out) {
		assertContains(
			content,
			"Code generated by scripts/gen-pdq.js; DO NOT EDIT.",
		);
		assertContains(content, "Copyright 2022 The Go Authors");
	}
});

test("each variant substitutes its own comparison and swap", () => {
	const [iface, func, ordered, cmp] = generateAll().map((o) => o.content);
	assertContains(iface, "data.Less(j, j-1)");
	assertContains(iface, "data.Swap(j, j-1)");
	assertContains(func, "func pdqsort_func(data lessSwap,");
	assertContains(ordered, "cmp.Less(data[j], data[j-1])");
	assertContains(ordered, "func pdqsortOrdered[E cmp.Ordered](data []E,");
	assertContains(cmp, "(cmp(data[j], data[j-1]) < 0)");
	assertContains(
		cmp,
		"func pdqsortCmpFunc[E any](data []E, a, b, limit int, cmp func(a, b E) int)",
	);
});

test("swaps and comparisons go through the index, never an address", () => {
	for (const { path, content } of generateAll()) {
		assert(
			!content.includes("&data["),
			`${path} takes the address of an element`,
		);
		assert(
			!content.includes("{{"),
			`${path} has an unexpanded template action`,
		);
	}
});

test("the variants cover the sort and slices packages", () => {
	assertEqual(
		VARIANTS.map((v) => v.path).join(","),
		"stdlib/sort/zsort_iface.go,stdlib/sort/zsort_func.go,stdlib/slices/zsort_ordered.go,stdlib/slices/zsort_cmp.go",
	);
});

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	process.exit((await summarize()) > 0 ? 1 : 0);
}
