#!/usr/bin/env node
// Generates the stdlib package tables in docs/language-support.md and
// docs/hybrid-wasm.md from stdlib/manifest.json. A member counts as
// available unless the coverage gate lists it as a gap
// (test/unit/types/stdlib-coverage.gaps.json), so the tables describe the
// current tree, not the plan. The tables sit between
// <!-- stdlib:begin --> and <!-- stdlib:end --> markers.
//
//   node scripts/docs-stdlib.js            rewrite the tables
//   node scripts/docs-stdlib.js --check    fail when a table is stale

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const MANIFEST_PATH = fileURLToPath(
	new URL("../stdlib/manifest.json", import.meta.url),
);
const GAPS_PATH = fileURLToPath(
	new URL("../test/unit/types/stdlib-coverage.gaps.json", import.meta.url),
);
const BEGIN = "<!-- stdlib:begin -->";
const END = "<!-- stdlib:end -->";

export const DOCS = [
	{
		path: fileURLToPath(
			new URL("../docs/language-support.md", import.meta.url),
		),
		table: "all",
	},
	{
		path: fileURLToPath(new URL("../docs/hybrid-wasm.md", import.meta.url)),
		table: "wasm",
	},
];

const NOTE =
	"<!-- Generated by `npm run docs:stdlib` from stdlib/manifest.json; do not edit. -->";

function gapSet(list) {
	return new Set(list ?? []);
}

function isGap(set, name) {
	return set.has("*") || set.has(name);
}

// Per-package counts over the manifest's member entries.
function packageStats(manifest, gaps) {
	const stats = new Map();
	const excludedPkgs = new Map();
	for (const e of manifest.entries) {
		if (e.kind === "package") {
			const cat = e.status.slice("excluded:".length);
			if (!excludedPkgs.has(cat)) excludedPkgs.set(cat, []);
			excludedPkgs.get(cat).push(e.pkg);
			continue;
		}
		if (!stats.has(e.pkg))
			stats.set(e.pkg, {
				total: 0,
				missing: 0,
				jsOnly: 0,
				excluded: 0,
				wasmTotal: 0,
				wasmMissing: 0,
			});
		const s = stats.get(e.pkg);
		if (e.status.startsWith("excluded:")) {
			s.excluded++;
			continue;
		}
		const missing = isGap(gapSet(gaps.missing?.[e.pkg]), e.name);
		s.total++;
		if (missing) s.missing++;
		if (e.status === "js") s.jsOnly++;
		if (e.status === "wasm" || e.status === "both") {
			s.wasmTotal++;
			if (missing || isGap(gapSet(gaps.wasm?.[e.pkg]), e.name)) s.wasmMissing++;
		}
	}
	return { stats, excludedPkgs };
}

const byName = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// The two Markdown tables: `all` for language-support.md, `wasm` for
// hybrid-wasm.md.
export function stdlibTables(manifest, gaps) {
	const { stats, excludedPkgs } = packageStats(manifest, gaps);
	const pkgs = [...stats.keys()].sort(byName);
	const all = [
		NOTE,
		"",
		`Members of each Go package (functions, types, methods, fields, constants and variables, as listed in Go's \`api/${manifest.go}.txt\`) that GoFront provides. **Available** counts what works today out of the members in scope; **Not yet** is scheduled in the [portable Go plan](../plans/v1.8.0/portable-go-plan.md); **JS-only** members (included in the first two columns) are not available in \`wasm\`/\`both\` packages by design; **Excluded** members are out of scope.`,
		"",
		"| Package | Available | Not yet | JS-only | Excluded |",
		"|---|---|---|---|---|",
		...pkgs.map((p) => {
			const s = stats.get(p);
			return `| \`${p}\` | ${s.total - s.missing} of ${s.total} | ${s.missing} | ${s.jsOnly} | ${s.excluded} |`;
		}),
		"",
		"Packages excluded as a whole, by reason:",
		"",
		"| Reason | Packages |",
		"|---|---|",
		...[...excludedPkgs.keys()].sort(byName).map(
			(cat) =>
				`| ${cat} | ${excludedPkgs
					.get(cat)
					.sort(byName)
					.map((p) => `\`${p}\``)
					.join(", ")} |`,
		),
	].join("\n");
	const wasmPkgs = pkgs.filter((p) => stats.get(p).wasmTotal > 0);
	const wasm = [
		NOTE,
		"",
		`Members of each Go package that \`wasm\` and \`both\` packages can use today, out of the members planned for them (JS-only and excluded members are not counted). **Not yet** is scheduled in the [portable Go plan](../plans/v1.8.0/portable-go-plan.md).`,
		"",
		"| Package | Available | Not yet |",
		"|---|---|---|",
		...wasmPkgs.map((p) => {
			const s = stats.get(p);
			return `| \`${p}\` | ${s.wasmTotal - s.wasmMissing} of ${s.wasmTotal} | ${s.wasmMissing} |`;
		}),
	].join("\n");
	return { all, wasm };
}

export function replaceBetweenMarkers(text, body, name) {
	const b = text.indexOf(BEGIN);
	const e = text.indexOf(END);
	if (b < 0 || e < b)
		throw new Error(`${name} has no ${BEGIN} / ${END} markers`);
	return `${text.slice(0, b + BEGIN.length)}\n${body}\n${text.slice(e)}`;
}

// [{ path, text }] with each doc's tables regenerated.
export function generateDocs() {
	const manifest = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));
	const gaps = JSON.parse(readFileSync(GAPS_PATH, "utf8"));
	const tables = stdlibTables(manifest, gaps);
	return DOCS.map(({ path, table }) => ({
		path,
		text: replaceBetweenMarkers(
			readFileSync(path, "utf8"),
			tables[table],
			path,
		),
	}));
}

function main(argv) {
	const stale = [];
	for (const { path, text } of generateDocs()) {
		if (readFileSync(path, "utf8") === text) continue;
		if (argv.includes("--check")) stale.push(path);
		else writeFileSync(path, text);
	}
	if (stale.length > 0) {
		console.error(
			`stale stdlib tables in ${stale.join(", ")}; run npm run docs:stdlib`,
		);
		process.exit(1);
	}
}

if (process.argv[1] === fileURLToPath(import.meta.url))
	main(process.argv.slice(2));
