//go:build gofront

//gofront:target both

// Package log implements a simple logging package. It defines a type, Logger,
// with methods for formatting output. It also has a predefined 'standard'
// Logger accessible through helper functions Print[f|ln], Fatal[f|ln], and
// Panic[f|ln].
//
// GoFront programs run on a single thread, so the Logger takes no locks. The
// Lshortfile and Llongfile flags print "???:0" because there is no call stack
// to read the file and line from. Fatal and its variants write the message and
// then exit the process in JavaScript; in WebAssembly, which cannot exit the
// host, they panic with the message.
package log

import (
	"fmt"
	"io"
	"os"
	"time"
)

// These flags define which text to prefix to each log entry generated by the
// Logger. Bits are or'ed together to control what's printed.
const (
	Ldate         = 1 << iota     // the date in the local time zone: 2009/01/23
	Ltime                         // the time in the local time zone: 01:23:23
	Lmicroseconds                 // microsecond resolution: 01:23:23.123123.  assumes Ltime.
	Llongfile                     // full file name and line number: /a/b/c/d.go:23
	Lshortfile                    // final file name element and line number: d.go:23. overrides Llongfile
	LUTC                          // if Ldate or Ltime is set, use UTC rather than the local time zone
	Lmsgprefix                    // move the "prefix" from the beginning of the line to before the message
	LstdFlags     = Ldate | Ltime // initial values for the standard logger
)

//gofront:intrinsic exit
func exit(code int)

// A Logger represents an active logging object that generates lines of
// output to an io.Writer.
type Logger struct {
	out    io.Writer // destination for output
	prefix string    // prefix on each line to identify the logger (but see Lmsgprefix)
	flag   int       // properties
}

// New creates a new Logger. The out variable sets the destination to which
// log data will be written. The prefix appears at the beginning of each
// generated log line, or after the log header if the Lmsgprefix flag is
// provided. The flag argument defines the logging properties.
func New(out io.Writer, prefix string, flag int) *Logger {
	l := new(Logger)
	l.SetOutput(out)
	l.SetPrefix(prefix)
	l.SetFlags(flag)
	return l
}

// SetOutput sets the output destination for the logger.
func (l *Logger) SetOutput(w io.Writer) {
	l.out = w
}

var std = New(os.Stderr, "", LstdFlags)

// Default returns the standard logger used by the package-level output
// functions.
func Default() *Logger { return std }

// The package-level functions go through stdLogger because a 'both' package
// may not call a pointer-receiver method on a package variable directly.
func stdLogger() *Logger { return std }

// itoa returns i as decimal digits padded with zeros to at least wid digits.
func itoa(i int, wid int) string {
	var b [20]byte
	bp := len(b) - 1
	for i >= 10 || wid > 1 {
		wid--
		q := i / 10
		b[bp] = byte('0' + i - q*10)
		bp--
		i = q
	}
	b[bp] = byte('0' + i)
	return string(b[bp:])
}

// formatHeader returns the prefix, date, time and file position that start a
// log line. Go reads the file and line from the call stack; there is none
// here, so they are "???" and 0.
func formatHeader(t time.Time, prefix string, flag int) string {
	h := ""
	if flag&Lmsgprefix == 0 {
		h += prefix
	}
	if flag&(Ldate|Ltime|Lmicroseconds) != 0 {
		if flag&LUTC != 0 {
			t = t.UTC()
		}
		if flag&Ldate != 0 {
			h += itoa(t.Year(), 4) + "/" + itoa(int(t.Month()), 2) + "/" + itoa(t.Day(), 2) + " "
		}
		if flag&(Ltime|Lmicroseconds) != 0 {
			h += itoa(t.Hour(), 2) + ":" + itoa(t.Minute(), 2) + ":" + itoa(t.Second(), 2)
			if flag&Lmicroseconds != 0 {
				h += "." + itoa(t.Nanosecond()/1000, 6)
			}
			h += " "
		}
	}
	if flag&(Lshortfile|Llongfile) != 0 {
		h += "???:0: "
	}
	if flag&Lmsgprefix != 0 {
		h += prefix
	}
	return h
}

// Output writes the output for a logging event. The string s contains the
// text to print after the prefix specified by the flags of the Logger. A
// newline is appended if the last character of s is not already a newline.
// Calldepth is ignored.
func (l *Logger) Output(calldepth int, s string) error {
	return l.output(s)
}

func (l *Logger) output(s string) error {
	line := formatHeader(time.Now(), l.prefix, l.flag) + s
	b := []byte(line)
	if len(b) == 0 || b[len(b)-1] != '\n' {
		b = append(b, '\n')
	}
	_, err := l.out.Write(b)
	return err
}

// Print calls l.Output to print to the logger.
// Arguments are handled in the manner of fmt.Print.
func (l *Logger) Print(v ...any) {
	l.output(fmt.Sprint(v...))
}

// Printf calls l.Output to print to the logger.
// Arguments are handled in the manner of fmt.Printf.
func (l *Logger) Printf(format string, v ...any) {
	l.output(fmt.Sprintf(format, v...))
}

// Println calls l.Output to print to the logger.
// Arguments are handled in the manner of fmt.Println.
func (l *Logger) Println(v ...any) {
	l.output(fmt.Sprintln(v...))
}

// fatal ends the program after the message was written: the process exits in
// JavaScript; in WebAssembly the intrinsic returns and the panic ends it.
func fatal(s string) {
	exit(1)
	panic(s)
}

// Fatal is equivalent to l.Print() followed by a call to os.Exit(1).
func (l *Logger) Fatal(v ...any) {
	s := fmt.Sprint(v...)
	l.output(s)
	fatal(s)
}

