// Slice, SliceStable and SliceIsSorted take the slice as a type parameter
// (S ~[]E) where Go takes `x any` and swaps through package reflect, which
// GoFront does not have.  Every call that is valid in Go (a slice argument)
// infers the same way; an interface value holding a slice is not accepted.

// Slice sorts the slice x given the provided less function.
// It panics if x is not a slice.
//
// The sort is not guaranteed to be stable: equal elements
// may be reversed from their original order.
// For a stable sort, use [SliceStable].
//
// The less function must satisfy the same requirements as
// the Interface type's Less method.
//
// Note: in many situations, the newer [slices.SortFunc] function is more
// ergonomic and runs faster.
func Slice[S ~[]E, E any](x S, less func(i, j int) bool) {
	swap := func(i, j int) { x[i], x[j] = x[j], x[i] }
	length := len(x)
	limit := bitsLen(uint(length))
	pdqsort_func(lessSwap{less, swap}, 0, length, limit)
}

// SliceStable sorts the slice x using the provided less
// function, keeping equal elements in their original order.
// It panics if x is not a slice.
//
// The less function must satisfy the same requirements as
// the Interface type's Less method.
//
// Note: in many situations, the newer [slices.SortStableFunc] function is more
// ergonomic and runs faster.
func SliceStable[S ~[]E, E any](x S, less func(i, j int) bool) {
	swap := func(i, j int) { x[i], x[j] = x[j], x[i] }
	stable_func(lessSwap{less, swap}, len(x))
}

// SliceIsSorted reports whether the slice x is sorted according to the provided less function.
// It panics if x is not a slice.
//
// Note: in many situations, the newer [slices.IsSortedFunc] function is more
// ergonomic and runs faster.
func SliceIsSorted[S ~[]E, E any](x S, less func(i, j int) bool) bool {
	for i := len(x) - 1; i > 0; i-- {
		if less(i, i-1) {
			return false
		}
	}
	return true
}
