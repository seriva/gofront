// xorshift paper: https://www.jstatsoft.org/article/view/v008i14/xorshift.pdf
type xorshift uint64

func (r *xorshift) Next() uint64 {
	*r ^= *r << 13
	*r ^= *r >> 7
	*r ^= *r << 17
	return uint64(*r)
}

// bitsLen is math/bits.Len for a uint.
func bitsLen(n uint) int {
	var l int
	for n > 0 {
		l++
		n >>= 1
	}
	return l
}

func nextPowerOfTwo(length int) uint {
	shift := uint(bitsLen(uint(length)))
	return uint(1 << shift)
}

// lessSwap is a pair of Less and Swap function for use with the
// auto-generated func-optimized variant of sort.go in
// zfuncversion.go.
type lessSwap struct {
	Less func(i, j int) bool
	Swap func(i, j int)
}

type reverse struct {
	// This embedded Interface permits Reverse to use the methods of
	// another Interface implementation.
	data Interface
}

// Len is the number of elements in the collection.
func (r *reverse) Len() int { return r.data.Len() }

// Less returns the opposite of the embedded implementation's Less method.
func (r *reverse) Less(i, j int) bool {
	return r.data.Less(j, i)
}

// Swap swaps the elements with indexes i and j.
func (r *reverse) Swap(i, j int) { r.data.Swap(i, j) }

// Reverse returns the reverse order for data.
func Reverse(data Interface) Interface {
	return &reverse{data: data}
}

// IsSorted reports whether data is sorted.
//
// Note: in many situations, the newer [slices.IsSortedFunc] function is more
// ergonomic and runs faster.
func IsSorted(data Interface) bool {
	n := data.Len()
	for i := n - 1; i > 0; i-- {
		if data.Less(i, i-1) {
			return false
		}
	}
	return true
}

